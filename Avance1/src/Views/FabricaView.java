    private void ButtonbasureroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonbasureroActionPerformed
        // TODO add your handling code here:
        int preciosumado = Integer.parseInt(precioSeleccionado.getText());
        // BORRAR LA INFO
        materialseleccionado.setText("");
        precioSeleccionado.setText("");
        // SUMAR EL PRECIO PERDIDO Y GUARDARLO EN EL LABEL
        perdidas = perdidas + preciosumado;
        jLabelPerdidas.setText("" + perdidas);
        // Traer nuevos datos
        Material actualizado = cola.desencolar();
        materialseleccionado.setText(actualizado.getNombre());
        precioSeleccionado.setText("" + actualizado.getValor());
    }//GEN-LAST:event_ButtonbasureroActionPerformed

